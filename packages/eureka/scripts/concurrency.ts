/**
 * Measure the pool-scaling curve offline.
 *
 *   bun run concurrency
 *
 * The same workload (3 companies, 2 challenges each) runs at pool sizes 1, 3
 * and 5. Mock latency is real sleeping, not a counter, so the wall-clock and
 * max-in-flight numbers are measured rather than asserted.
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

interface TraceLine {
  type: string;
  producer: string;
}

interface Result {
  pools: number;
  wallClockMs: number;
  maxInFlight: number;
  modelCalls: number;
  inputTokens: number;
  outputTokens: number;
  costUsd: number;
  runId: string;
}

const ROOT = resolve(import.meta.dir, "..");
const LATENCY_MS = 50;
const WORKLOAD = ["--companies=3", "--challenges=2", "--candidates=6", "--profile=3"];

const maxInFlight = (lines: TraceLine[]): number => {
  let live = 0;
  let peak = 0;
  for (const line of lines) {
    if (line.type === "inference.started") {
      live += 1;
      peak = Math.max(peak, live);
    } else if (line.type === "inference.completed") {
      live -= 1;
    }
  }
  return peak;
};

const run = (pools: number): Result => {
  const args = [
    "src/index.ts",
    "run",
    ...WORKLOAD,
    `--pools=profiler:${pools},analyst:${pools},matchmaker:${pools},writer:${pools},critic:${pools}`,
    `--mock-latency=${LATENCY_MS}`,
  ];
  const child = spawnSync(process.execPath, args, {
    cwd: ROOT,
    env: { ...process.env, MOCK: "1" },
    encoding: "utf8",
    timeout: 120_000,
  });
  const output = `${child.stdout ?? ""}${child.stderr ?? ""}`;
  const match = /trace\s+runs\/([^\s]+)\/trace\.jsonl/.exec(output);
  if (!match) throw new Error(`run at pools=${pools} produced no trace:\n${output.slice(-3000)}`);
  const runId = match[1]!;
  const lines = readFileSync(resolve(ROOT, "runs", runId, "trace.jsonl"), "utf8")
    .split("\n")
    .filter(Boolean)
    .map((line) => JSON.parse(line) as TraceLine);
  const summary = JSON.parse(readFileSync(resolve(ROOT, "runs", runId, "run.json"), "utf8")).summary;
  return {
    pools,
    wallClockMs: summary.elapsedMs,
    maxInFlight: maxInFlight(lines),
    modelCalls: summary.modelCalls,
    inputTokens: summary.inputTokens,
    outputTokens: summary.outputTokens,
    costUsd: summary.costUsd,
    runId,
  };
};

const results = [1, 3, 5].map(run);

for (let index = 1; index < results.length; index += 1) {
  const previous = results[index - 1]!;
  const current = results[index]!;
  if (current.maxInFlight < previous.maxInFlight) {
    throw new Error(`max in-flight fell from ${previous.maxInFlight} to ${current.maxInFlight}`);
  }
  if (current.wallClockMs > previous.wallClockMs * 1.15) {
    throw new Error(
      `wall clock did not fall with more workers: ${previous.wallClockMs}ms -> ${current.wallClockMs}ms`,
    );
  }
}

const payload = {
  generatedAt: new Date().toISOString(),
  workload: {
    command: `MOCK=1 bun src/index.ts run ${WORKLOAD.join(" ")} --mock-latency=${LATENCY_MS} --pools=<n>`,
    companies: 3,
    challengesPerCompany: 2,
    mockLatencyMs: LATENCY_MS,
  },
  results,
};
writeFileSync(resolve(ROOT, "eval/concurrency.json"), `${JSON.stringify(payload, null, 2)}\n`);

const rows = results
  .map(
    (row) =>
      `| ${row.pools} | ${row.wallClockMs} ms | ${row.maxInFlight} | ${row.modelCalls} | ${row.inputTokens + row.outputTokens} | $${row.costUsd.toFixed(4)} |`,
  )
  .join("\n");

writeFileSync(
  resolve(ROOT, "eval/concurrency.md"),
  [
    "# Pool-scaling curve",
    "",
    `Same workload at each pool size: 3 companies × 2 challenges, deterministic mock, ${LATENCY_MS} ms per model call.`,
    "Max in-flight is derived from `inference.started` minus `inference.completed` in the trace.",
    "",
    "| Pools (workers per role) | Wall clock | Max in flight | Model calls | Tokens | Cost |",
    "| --- | --- | --- | --- | --- | --- |",
    rows,
    "",
    `Generated by \`bun run concurrency\` on ${payload.generatedAt.slice(0, 10)}.`,
    "",
  ].join("\n"),
);

console.log("\n  pools  wall     in-flight  calls  cost");
for (const row of results) {
  console.log(
    `  ${String(row.pools).padStart(5)}  ${String(row.wallClockMs).padStart(6)}ms  ${String(row.maxInFlight).padStart(9)}  ${String(row.modelCalls).padStart(5)}  $${row.costUsd.toFixed(4)}`,
  );
}
console.log("\n  wrote eval/concurrency.json and eval/concurrency.md\n");
